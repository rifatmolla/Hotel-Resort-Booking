import { SupportedCurrency, SupportedLanguage } from '../types';

export const CURRENCY_RATES: Record<SupportedCurrency, { rate: number; symbol: string; code: SupportedCurrency }> = {
  USD: { rate: 1.0, symbol: '$', code: 'USD' },
  EUR: { rate: 0.92, symbol: '€', code: 'EUR' },
  GBP: { rate: 0.78, symbol: '£', code: 'GBP' },
  JPY: { rate: 155.0, symbol: '¥', code: 'JPY' },
  CAD: { rate: 1.36, symbol: 'CA$', code: 'CAD' },
};

export function formatPrice(amountInUSD: number, currency: SupportedCurrency): string {
  const { rate, symbol } = CURRENCY_RATES[currency] || CURRENCY_RATES.USD;
  const converted = Math.round(amountInUSD * rate);
  if (currency === 'JPY') {
    return `${symbol}${converted.toLocaleString()}`;
  }
  return `${symbol}${converted.toLocaleString()}`;
}

